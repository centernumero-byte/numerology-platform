    1: { title: "Воля и личность", el: "Ян Воды", plus: "сила воли, характер, лидерство, независимость, стремление проявить себя", minus: "гордыня, одиночество, показное лидерство" },
    2: { title: "Жизненная энергия и эмоции", el: "Ян Металла", plus: "чувствительность, отзывчивость, красноречие, гибкость, оптимизм", minus: "сверхчувствительность, нестабильные эмоции, пассивность" },
    3: { title: "Интерес и знания", el: "Ян Земли", plus: "любознательность, техничность, умение доводить дело до конца, красиво говорить и делать", minus: "распыление интересов, критиканство, неуместный контроль" },
    4: { title: "Тело и будущее", el: "Ян Огня", plus: "крепкое тело, выносливость, образное мышление, видение будущего, стратегия", minus: "испытания здоровьем и условиями жизни, скованность, педантизм" },
    5: { title: "Логика и интуиция", el: "Инь Земли", plus: "быстрота реакции, интуиция в действиях, понимание сути, наблюдательность", minus: "спешка, рассеянность, переменчивость" },
