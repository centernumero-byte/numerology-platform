  // Числовой ряд: дата (день и месяц без ведущих нулей) + 4 дополнительных числа
  function numericRow(day, month, year) {
    const dateDigits = digitsOf(day).concat(digitsOf(month), digitsOf(year));
    const n1 = sum(dateDigits);                       // 1-е: сумма всех цифр даты
    const n2 = sum(digitsOf(n1));                     // 2-е: сумма цифр 1-го
    const n3 = Math.abs(n1 - 2 * dateDigits[0]);      // 3-е: 1-е минус первая цифра даты × 2
    const n4 = sum(digitsOf(n3));                     // 4-е: сумма цифр 3-го
    const allDigits = dateDigits.concat(digitsOf(n1), digitsOf(n2), digitsOf(n3), digitsOf(n4));
    const counts = Array(10).fill(0);
    allDigits.forEach((d) => counts[d]++);
    return { dateDigits, n1, n2, n3, n4, counts, allDigits };
  }

  // Энергетический режим первоэлемента по количеству цифр Инь (слева) и Ян (справа)
  function regime(yinCount, yangCount) {
    const total = yinCount + yangCount;
    if (total === 0) return { key: "min", name: "Минимальный" };
    if (yinCount === 0 || yangCount === 0) return { key: "midmin", name: "Средне-минимальный", side: yinCount ? "инь" : "ян" };
    if (yinCount === yangCount) return { key: "den", name: "Дэн" };
    if (total >= 5) return { key: "max", name: "Максимальный", side: yinCount > yangCount ? "инь" : "ян" };
    return { key: "mid", name: "Средний", side: yinCount > yangCount ? "инь" : "ян" };
  }

